test_that("table cells keep spans, markers, missing tokens and footnotes", {
  doc <- sc_parse(fixture("trial_tables.pdf"))
  tb <- sc_tables(doc)
  expect_equal(nrow(tb), 2L)
  expect_identical(tb$label, c("Table 1", "Table 2"))
  c1 <- sc_table_cells(doc, "Table 1")
  span <- c1[c1$text == "Treatment group", ]
  expect_equal(span$col_span, 2L)
  expect_true(span$is_header)
  expect_true(any(c1$missing_token))
  expect_identical(c1$markers[grepl("^Diabetes", c1$text)], "a")
  expect_gte(nrow(sc_table_footnotes(doc, "Table 1")), 1L)
  expect_match(sc_table_caption(doc, "Table 2"), "Outcomes")
  df <- sc_table_to_dataframe(doc, "Table 2")
  expect_equal(nrow(df), 3L)
  expect_true(any(grepl("HR", names(df))))
  m <- sc_table_to_matrix(doc, "Table 1", fill_spans = TRUE)
  expect_identical(m[1, 2], m[1, 3])
  expect_error(sc_table_to_matrix(doc, "Table 9"), "No table")
})

test_that("continued tables are joined only when certain", {
  doc <- sc_parse(fixture("figure_equation.pdf"))
  tb <- sc_tables(doc)
  expect_equal(nrow(tb), 2L)
  expect_identical(tb$continuation_status[2], "joined")
  expect_identical(tb$continuation_of[2], tb$table_id[1])
  joined <- sc_table_to_dataframe(doc, "Table 3")
  alone <- sc_table_to_dataframe(doc, "Table 3", join_continuations = FALSE)
  expect_gt(nrow(joined), nrow(alone))
})
